"""Generate the S3 forward gait header; values are in hundredths of a degree."""
from pathlib import Path

FRAME_MS = 20
PHASE_MS = (320, 160, 360, 280, 400)
HALF_MS = sum(PHASE_MS)
CYCLE_MS = 2 * HALF_MS


def ease(x):
    return x * x * (3 - 2 * x)


def pose(ms):
    half, t = divmod(ms, HALF_MS)
    sign = 1 if half % 2 == 0 else -1
    hip0 = 0 if half == 0 else -15
    # Hip yaw, stance ankle, swing ankle. Set the foot down in two stages:
    # approach the ground, then roll both soles level over the final 400 ms.
    points = [(hip0, 0, 0), (hip0, 10, 17), (hip0, 10, 10),
              (15, 10, 10), (15, 10, 17), (15, 0, 0)]
    for i, span in enumerate(PHASE_MS):
        if t < span:
            u = ease(t / span)
            h, a, b = [sign * (v + (w - v) * u)
                       for v, w in zip(points[i], points[i + 1])]
            gain = ease(min(1, ms / CYCLE_MS))
            return tuple(round(v * gain * 100) for v in
                         ((h, h, a, b) if sign == 1 else (h, h, b, a)))
        t -= span


def main():
    lines = ['#pragma once', '#include <stdint.h>',
             '// Generated by generate_walk.py. Left hip, right hip, left foot, right foot.',
             f'constexpr uint16_t FRAME_MS = {FRAME_MS};']
    for name, base in [('STARTUP', 0), ('CYCLE', CYCLE_MS)]:
        lines.extend([f'constexpr uint16_t {name}_FRAMES = {CYCLE_MS // FRAME_MS};',
                      f'constexpr int16_t {name}_CDEG[][4] = {{'])
        for t in range(base, base + CYCLE_MS, FRAME_MS):
            lines.append('  {' + ', '.join(map(str, pose(t))) + '},')
        lines.append('};')
    (Path(__file__).parent / 'S3MediaServo' / 'walk_profile.h').write_bytes(
        ('\n'.join(lines) + '\n').encode())


if __name__ == '__main__':
    main()
